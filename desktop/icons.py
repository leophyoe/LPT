# In-memory pixmap cache: (name, color_hex, size) -> QPixmap
_PIXMAP_CACHE: Dict[Tuple[str, str, int], QPixmap] = {}


def get_default_color() -> str:
    """Returns the default icon color for the currently active theme mode."""
    mode = ThemeManager.instance().current_mode
    return "#CBD5E1" if mode == ThemeMode.DARK else "#334155"


def get_pixmap(name: str, color: Optional[str] = None, size: int = 18) -> QPixmap:
    """Renders a Lucide SVG icon into a high-DPI QPixmap."""
    resolved_color = color or get_default_color()
    cache_key = (name, resolved_color, size)

    if cache_key in _PIXMAP_CACHE:
        return _PIXMAP_CACHE[cache_key]

    path_data = LUCIDE_PATHS.get(name)
    if not path_data:
        # Fallback empty transparent pixmap
        pm = QPixmap(size, size)
        pm.fill(QColor(0, 0, 0, 0))
        return pm

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="{resolved_color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
{path_data}
</svg>"""

    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    pix = QPixmap(size, size)
    pix.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pix)
    renderer.render(painter)
    painter.end()

    _PIXMAP_CACHE[cache_key] = pix
    return pix


def get_icon(name: str, color: Optional[str] = None, size: int = 18) -> QIcon:
    """Returns a QIcon wrapping the rendered Lucide SVG pixmap."""
    pix = get_pixmap(name, color=color, size=size)
    return QIcon(pix)


def clear_cache() -> None:
    """Clears the icon cache, typically called upon theme switches."""
    _PIXMAP_CACHE.clear()

